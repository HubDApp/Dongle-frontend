#!/usr/bin/env node
/**
 * Generates form schema documentation from the Zod schemas (Issue #581).
 *
 * Usage:
 *   node scripts/generate-schema-docs.mjs                      # markdown → docs/form-schemas.md
 *   node scripts/generate-schema-docs.mjs --format json
 *   node scripts/generate-schema-docs.mjs --format html --out docs/form-schemas.html
 *   node scripts/generate-schema-docs.mjs --check              # fail if the committed docs are stale
 *
 * `--check` is the "updates automatically" half of the acceptance criteria: run
 * it in CI and a schema change that does not regenerate the docs fails the
 * build, so the two cannot drift. Generating on every commit via a hook would
 * also work, but a check is reviewable — the regenerated diff shows up in the PR
 * rather than appearing silently.
 */

import { writeFile, readFile, mkdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { register } from "node:module";

const HERE = dirname(fileURLToPath(import.meta.url));
/** The Next app root — `dongle/`. Schemas are resolved relative to this. */
const APP_ROOT = resolve(HERE, "..");
/** Repository root. Documentation lives in the top-level `docs/`, not per-package. */
const REPO_ROOT = resolve(APP_ROOT, "..");

const FORMATS = { markdown: "md", json: "json", html: "html" };

function parseArgs(argv) {
  const args = { format: "markdown", out: null, check: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--check") args.check = true;
    else if (arg === "--format") args.format = argv[++i];
    else if (arg === "--out") args.out = argv[++i];
    else if (arg === "--help" || arg === "-h") args.help = true;
  }
  return args;
}

const args = parseArgs(process.argv.slice(2));

if (args.help) {
  console.log(
    [
      "Generate form schema documentation from Zod schemas.",
      "",
      "  --format markdown|json|html   output format (default: markdown)",
      "  --out <path>                  output file (default: docs/form-schemas.<ext>)",
      "  --check                       exit 1 if the committed file is stale",
    ].join("\n"),
  );
  process.exit(0);
}

if (!Object.hasOwn(FORMATS, args.format)) {
  console.error(
    `Unknown format '${args.format}'. Expected one of: ${Object.keys(FORMATS).join(", ")}`,
  );
  process.exit(1);
}

// The schemas are TypeScript. tsx is registered as a loader hook so this script
// can import them directly rather than requiring a build step first — a docs
// generator that only runs after `next build` is one nobody runs.
try {
  register("tsx/esm", import.meta.url);
} catch (err) {
  console.error(
    "Could not register the tsx loader. Install dev dependencies first (`npm install`).",
  );
  console.error(err.message);
  process.exit(1);
}

const { documentSchema, render } = await import("../lib/schemas/document.ts");
const { DOCUMENTED_SCHEMAS } = await import("../lib/schemas/registry.ts");

const outPath =
  args.out ?? resolve(REPO_ROOT, `docs/form-schemas.${FORMATS[args.format]}`);

const docs = DOCUMENTED_SCHEMAS.map(({ name, schema, description }) =>
  documentSchema(schema, name, description),
);

let output;
if (args.format === "json") {
  // One array rather than concatenated JSON documents, so the file is parseable.
  output = `${JSON.stringify(
    docs.map((doc) => JSON.parse(render(doc, "json"))),
    null,
    2,
  )}\n`;
} else {
  const header =
    args.format === "markdown"
      ? [
          "<!-- Generated by scripts/generate-schema-docs.mjs — do not edit by hand. -->",
          "<!-- Regenerate with: npm run docs:schemas -->",
          "",
          "# Form schemas",
          "",
          "Derived from the Zod schemas in `lib/schemas/`. Every field, rule and",
          "example below comes from the schema itself, so this file cannot disagree",
          "with what the app actually validates.",
          "",
        ].join("\n")
      : "<!-- Generated by scripts/generate-schema-docs.mjs — do not edit by hand. -->\n";

  output = `${header}\n${docs.map((doc) => render(doc, args.format)).join("\n")}\n`;
}

if (args.check) {
  let existing = null;
  try {
    existing = await readFile(outPath, "utf8");
  } catch {
    console.error(`✗ ${outPath} does not exist. Run: npm run docs:schemas`);
    process.exit(1);
  }

  if (existing !== output) {
    console.error(
      `✗ ${outPath} is out of date with the Zod schemas.\n  Run: npm run docs:schemas`,
    );
    process.exit(1);
  }

  console.log(`✓ ${outPath} is up to date (${docs.length} schema(s))`);
  process.exit(0);
}

await mkdir(dirname(outPath), { recursive: true });
await writeFile(outPath, output, "utf8");

const fieldCount = docs.reduce((sum, doc) => sum + doc.fields.length, 0);
console.log(
  `✓ Wrote ${outPath} — ${docs.length} schema(s), ${fieldCount} field(s), format: ${args.format}`,
);
